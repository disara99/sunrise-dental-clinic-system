private void loadReceptionists() {

    DefaultTableModel model =
            (DefaultTableModel) tblReceptionists.getModel();

    model.setRowCount(0);

    List<Receptionist> receptionists =
            receptionistDAO.getAllReceptionists();

    for (Receptionist receptionist : receptionists) {

        model.addRow(new Object[]{
            receptionist.getReceptionistId(),
            receptionist.getUserId(),
            receptionist.getName(),
            receptionist.getEmail(),
            receptionist.getContactNo(),
            receptionist.getStatus()
        });
    }
    
}
