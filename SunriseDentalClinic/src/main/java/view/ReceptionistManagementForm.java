    private void btnDeactivateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeactivateActionPerformed
 int selectedRow = tblReceptionists.getSelectedRow();

    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(
                this,
                "Please select a receptionist to deactivate."
        );
        return;
    }

    int userId = Integer.parseInt(
            tblReceptionists.getValueAt(selectedRow, 0).toString()
    );

    int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to deactivate this receptionist?",
            "Confirm Deactivation",
            JOptionPane.YES_NO_OPTION
    );

    if (confirm == JOptionPane.YES_OPTION) {

        UserDAO userDAO = new UserDAO();

        if (userDAO.deactivateUser(userId)) {

            JOptionPane.showMessageDialog(
                    this,
                    "Receptionist deactivated successfully."
            );

            loadReceptionists();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Failed to deactivate receptionist."
            );
        }
    }       // TODO add your handling code here:
    }//GEN-LAST:event_btnDeactivateActionPerformed

