    private void loadLoggedInDentist() {

    if (loggedInUser == null) {

        JOptionPane.showMessageDialog(
                this,
                "Logged-in user information is missing.",
                "Error",
                JOptionPane.ERROR_MESSAGE
        );

        return;
    }

    loggedInDentist =
            dentistDAO.findByUserId(
                    loggedInUser.getUserId()
            );

    if (loggedInDentist == null) {

        JOptionPane.showMessageDialog(
                this,
                "Dentist profile not found.",
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}
    private void loadPatients() {

    cmbPatient.removeAllItems();
    cmbPatient.addItem("Select Patient");

    List<Patient> patients =
            patientDAO.getAllPatients();

    for (Patient patient : patients) {

        cmbPatient.addItem(
                patient.getPatientId()
                + " - "
                + patient.getName()
        );
    }
}
    private void loadAppointments() {

    cmbAppointment.removeAllItems();
    cmbAppointment.addItem("Select Appointment");

    if (loggedInDentist == null) {
        return;
    }

    List<Appointment> appointments =
            appointmentDAO.getAppointmentsByDentistId(
                    loggedInDentist.getDentistId()
            );

    for (Appointment appointment : appointments) {

        cmbAppointment.addItem(
                appointment.getAppointmentId()
                + " - "
                + appointment.getAppointmentNo()
        );
    }
}
    private void loadMedicalRecords() {

    DefaultTableModel tableModel =
            (DefaultTableModel) tblMedicalRecords.getModel();

    tableModel.setRowCount(0);

    if (loggedInDentist == null) {
        return;
    }

    List<MedicalRecord> records =
            medicalRecordDAO.getRecordsByDentistId(
                    loggedInDentist.getDentistId()
            );

    for (MedicalRecord record : records) {

        String patientName = "";
        String appointmentNo = "";

        Patient patient =
                patientDAO.findById(
                        record.getPatientId()
                );

        if (patient != null) {
            patientName = patient.getName();
        }

        Appointment appointment =
                appointmentDAO.findById(
                        record.getAppointmentId()
                );

        if (appointment != null) {
            appointmentNo =
                    appointment.getAppointmentNo();
        }

        tableModel.addRow(new Object[]{
            record.getRecordId(),
            patientName,
            appointmentNo,
            record.getDiagnosis(),
            record.getTreatmentNotes(),
            record.getPrescription(),
            record.getRecordDate()
        });
    }
}

