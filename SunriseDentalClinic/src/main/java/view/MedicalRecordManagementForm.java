private boolean validatePatientAppointment() {

    if (cmbPatient.getSelectedIndex() == 0) {
        JOptionPane.showMessageDialog(
                this,
                "Please select a patient.",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
        );
        return false;
    }

    if (cmbAppointment.getSelectedIndex() == 0) {
        JOptionPane.showMessageDialog(
                this,
                "Please select an appointment.",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
        );
        return false;
    }

    try {

        String patientItem =
                cmbPatient.getSelectedItem().toString();

        int selectedPatientId =
                Integer.parseInt(
                        patientItem.split(" - ")[0]
                );

        String appointmentItem =
                cmbAppointment.getSelectedItem().toString();

        int selectedAppointmentId =
                Integer.parseInt(
                        appointmentItem.split(" - ")[0]
                );

        Appointment appointment =
                appointmentDAO.findById(
                        selectedAppointmentId
                );

        if (appointment == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "Selected appointment was not found.",
                    "Validation Error",
                    JOptionPane.WARNING_MESSAGE
            );

            return false;
        }

        if (appointment.getPatientId() != selectedPatientId) {

            JOptionPane.showMessageDialog(
                    this,
                    "The selected patient does not belong to "
                    + "the selected appointment.",
                    "Validation Error",
                    JOptionPane.WARNING_MESSAGE
            );

            return false;
        }

        // Also make sure appointment belongs to logged-in dentist
        if (loggedInDentist != null
                && appointment.getDentistId()
                != loggedInDentist.getDentistId()) {

            JOptionPane.showMessageDialog(
                    this,
                    "You can only create records for "
                    + "your own appointments.",
                    "Access Denied",
                    JOptionPane.ERROR_MESSAGE
            );

            return false;
        }

        return true;

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Invalid patient or appointment selection.",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
        );

        return false;
    }
}
