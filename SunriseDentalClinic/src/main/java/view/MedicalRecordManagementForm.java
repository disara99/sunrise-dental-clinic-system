    private void tblMedicalRecordsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblMedicalRecordsMouseClicked
 int selectedRow = tblMedicalRecords.getSelectedRow();

    if (selectedRow < 0) {
        return;
    }

    // Record ID
    txtRecordId.setText(
            tblMedicalRecords.getValueAt(selectedRow, 0).toString()
    );

    // Patient
    String patientName =
            tblMedicalRecords.getValueAt(selectedRow, 1).toString();

    selectComboByName(cmbPatient, patientName);

    // Appointment
    String appointmentNo =
            tblMedicalRecords.getValueAt(selectedRow, 2).toString();

    selectAppointmentByNo(cmbAppointment, appointmentNo);

    // Diagnosis
    txtDiagnosis.setText(
            tblMedicalRecords.getValueAt(selectedRow, 3).toString()
    );

    // Treatment Notes
    txtTreatmentNotes.setText(
            tblMedicalRecords.getValueAt(selectedRow, 4).toString()
    );

    // Prescription
    txtPrescription.setText(
            tblMedicalRecords.getValueAt(selectedRow, 5).toString()
    );

    // Record Date
    Object recordDate =
            tblMedicalRecords.getValueAt(selectedRow, 6);

    txtRecordDate.setText(
            recordDate != null ? recordDate.toString() : ""
    );        // TODO add your handling code here:
    }//GEN-LAST:event_tblMedicalRecordsMouseClicked

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
// Make sure a dentist is logged in
    if (loggedInDentist == null) {
        JOptionPane.showMessageDialog(
                this,
                "Dentist information is not available.",
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    // Check selections
    if (cmbPatient.getSelectedIndex() == 0) {
        JOptionPane.showMessageDialog(
                this,
                "Please select a patient.",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    if (cmbAppointment.getSelectedIndex() == 0) {
        JOptionPane.showMessageDialog(
                this,
                "Please select an appointment.",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String diagnosis = txtDiagnosis.getText().trim();
    String treatmentNotes = txtTreatmentNotes.getText().trim();
    String prescription = txtPrescription.getText().trim();
    String recordDateText = txtRecordDate.getText().trim();

    if (diagnosis.isEmpty() || treatmentNotes.isEmpty()
            || recordDateText.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Please fill Diagnosis, Treatment Notes and Record Date.",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    try {

        // Get patient ID from Patient combo
        String patientItem =
                cmbPatient.getSelectedItem().toString();

        int patientId =
                Integer.parseInt(
                        patientItem.split(" - ")[0]
                );

        // Get appointment ID from Appointment combo
        String appointmentItem =
                cmbAppointment.getSelectedItem().toString();

        int appointmentId =
                Integer.parseInt(
                        appointmentItem.split(" - ")[0]
                );

        // Record date
        Date recordDate =
                Date.valueOf(recordDateText);

        // Create medical record using logged-in dentist
        MedicalRecord record = new MedicalRecord(
                0,
                patientId,
                loggedInDentist.getDentistId(),
                appointmentId,
                diagnosis,
                treatmentNotes,
                prescription,
                recordDate
        );

        boolean result =
                medicalRecordDAO.insertMedicalRecord(record);

        if (result) {

            JOptionPane.showMessageDialog(
                    this,
                    "Medical record added successfully."
            );

            loadMedicalRecords();
            clearFields();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Failed to add medical record.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Invalid patient or appointment ID.",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
        );

    } catch (IllegalArgumentException e) {

        JOptionPane.showMessageDialog(
                this,
                "Invalid record date.\n\n"
                + "Use format: YYYY-MM-DD\n"
                + "Example: 2026-09-04",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
        );
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnAddActionPerformed

