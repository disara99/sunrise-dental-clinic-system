                Double.parseDouble(
                        txtConsultationFee.getText().trim()
                );

        double treatmentFee =
                Double.parseDouble(
                        txtTreatmentFee.getText().trim()
                );

        double totalAmount =
                consultationFee + treatmentFee;

        String paymentStatus =
                cmbPaymentStatus.getSelectedItem().toString();

        Date billDate =
                Date.valueOf(
                        txtBillDate.getText().trim()
                );

        Bill bill = new Bill(
                billId,
                appointmentId,
                consultationFee,
                treatmentFee,
                totalAmount,
                paymentStatus,
                billDate
        );

