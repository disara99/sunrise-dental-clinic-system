    private void loadAppointments() {

       cmbAppointment.removeAllItems();

    cmbAppointment.addItem("Select Appointment");

    List<Appointment> appointments =
            appointmentDAO.getAllAppointments();

    for (Appointment appointment : appointments) {

        cmbAppointment.addItem(
                appointment.getAppointmentId()
                + " - "
                + appointment.getAppointmentNo()
        );
    }
}
    private void loadBills() {

    DefaultTableModel tableModel =
            (DefaultTableModel) tblBills.getModel();

    tableModel.setRowCount(0);

    List<Bill> bills = billDAO.getAllBills();

    for (Bill bill : bills) {

        String appointmentNo = "";
        String patientName = "";
        String dentistName = "";
        String treatmentName = "";

        Appointment appointment =
                appointmentDAO.findById(
                        bill.getAppointmentId()
                );

        if (appointment != null) {

            appointmentNo =
                    appointment.getAppointmentNo();

            Patient patient =
                    patientDAO.findById(
                            appointment.getPatientId()
                    );

            if (patient != null) {
                patientName = patient.getName();
            }

            Dentist dentist =
                    dentistDAO.findById(
                            appointment.getDentistId()
                    );

            if (dentist != null) {
                dentistName = dentist.getName();
            }

            Treatment treatment =
                    treatmentDAO.findById(
                            appointment.getTreatmentId()
                    );

            if (treatment != null) {
                treatmentName = treatment.getTreatmentName();
            }
        }

        tableModel.addRow(new Object[]{
            bill.getBillId(),
            appointmentNo,
            patientName,
            dentistName,
            treatmentName,
            bill.getConsultationFee(),
            bill.getTreatmentFee(),
            bill.getTotalAmount(),
            bill.getPaymentStatus(),
            bill.getBillDate()
        });
    }
}

