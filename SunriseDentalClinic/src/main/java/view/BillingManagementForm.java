    private void btnGenerateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerateActionPerformed
if (cmbAppointment.getSelectedIndex() == 0) {

        JOptionPane.showMessageDialog(
                this,
                "Please select an appointment.",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    try {

        String selectedItem =
                cmbAppointment.getSelectedItem().toString();

        int appointmentId =
                Integer.parseInt(
                        selectedItem.split(" - ")[0]
                );

        // Prevent duplicate bills
        Bill existingBill =
                billDAO.findByAppointmentId(appointmentId);

        if (existingBill != null) {

            JOptionPane.showMessageDialog(
                    this,
                    "A bill already exists for this appointment.",
                    "Duplicate Bill",
                    JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        double consultationFee =
                Double.parseDouble(
                        txtConsultationFee.getText().trim()
                );

        double treatmentFee =
                Double.parseDouble(
                        txtTreatmentFee.getText().trim()
                );

        double totalAmount =
                consultationFee + treatmentFee;

        Date billDate =
                new Date(System.currentTimeMillis());

        String paymentStatus =
                cmbPaymentStatus.getSelectedItem().toString();

        Bill bill = new Bill(
                0,
                appointmentId,
                consultationFee,
                treatmentFee,
                totalAmount,
                paymentStatus,
                billDate
        );

        boolean result =
                billDAO.insertBill(bill);

        if (result) {

            JOptionPane.showMessageDialog(
                    this,
                    "Bill generated successfully."
            );

            loadBills();
            clearFields();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Failed to generate bill.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Invalid fee value.",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
        );
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnGenerateActionPerformed

