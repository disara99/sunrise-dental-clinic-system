    private void tblAppointmentsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblAppointmentsMouseClicked
 int selectedRow = tblAppointments.getSelectedRow();

    if (selectedRow < 0) {
        return;
    }

    // Appointment ID
    txtAppointmentId.setText(
            tblAppointments.getValueAt(selectedRow, 0).toString()
    );

    // Appointment Number
    txtAppointmentNo.setText(
            tblAppointments.getValueAt(selectedRow, 1).toString()
    );

    // Patient
    String patientName =
            tblAppointments.getValueAt(selectedRow, 2).toString();

    selectComboByName(cmbPatient, patientName);

    // Dentist
    String dentistName =
            tblAppointments.getValueAt(selectedRow, 3).toString();

    selectComboByName(cmbDentist, dentistName);

    // Treatment
    String treatmentName =
            tblAppointments.getValueAt(selectedRow, 4).toString();

    selectComboByName(cmbTreatment, treatmentName);

    // Date
    Object date =
            tblAppointments.getValueAt(selectedRow, 5);

    txtAppointmentDate.setText(
            date != null ? date.toString() : ""
    );

    // Time
    Object time =
            tblAppointments.getValueAt(selectedRow, 6);

    txtAppointmentTime.setText(
            time != null ? time.toString() : ""
    );

    // Status
    Object status =
            tblAppointments.getValueAt(selectedRow, 7);

    if (status != null) {
        cmbStatus.setSelectedItem(status.toString());
    }

    // Created By
    Object createdBy =
            tblAppointments.getValueAt(selectedRow, 8);

    txtCreatedBy.setText(
            createdBy != null ? createdBy.toString() : ""
    );        // TODO add your handling code here:
    }//GEN-LAST:event_tblAppointmentsMouseClicked

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
   String appointmentNo = txtAppointmentNo.getText().trim();
    String patientItem = cmbPatient.getSelectedItem().toString();
    String dentistItem = cmbDentist.getSelectedItem().toString();
    String treatmentItem = cmbTreatment.getSelectedItem().toString();
    String dateText = txtAppointmentDate.getText().trim();
    String timeText = txtAppointmentTime.getText().trim();
    String status = cmbStatus.getSelectedItem().toString();
    String createdByText = txtCreatedBy.getText().trim();

    // Basic validation
    if (appointmentNo.isEmpty()
            || dateText.isEmpty()
            || timeText.isEmpty()
            || createdByText.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Please fill all required fields.",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    if (cmbPatient.getSelectedIndex() == 0
            || cmbDentist.getSelectedIndex() == 0
            || cmbTreatment.getSelectedIndex() == 0) {

        JOptionPane.showMessageDialog(
                this,
                "Please select Patient, Dentist and Treatment.",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    try {

        // Get IDs from combo boxes
        int patientId = Integer.parseInt(
                patientItem.split(" - ")[0]
        );

        int dentistId = Integer.parseInt(
                dentistItem.split(" - ")[0]
        );

        int treatmentId = Integer.parseInt(
                treatmentItem.split(" - ")[0]
        );

        // Convert date
        Date appointmentDate = Date.valueOf(dateText);

        // Convert time
        Time appointmentTime = Time.valueOf(timeText);

        // Created By
        int createdBy = Integer.parseInt(createdByText);

        Appointment appointment = new Appointment(
                0,
                appointmentNo,
                patientId,
                dentistId,
                treatmentId,
                appointmentDate,
                appointmentTime,
                status,
                createdBy
        );

        boolean result =
                appointmentDAO.insertAppointment(appointment);

        if (result) {

            JOptionPane.showMessageDialog(
                    this,
                    "Appointment added successfully."
            );

            loadAppointments();
            clearFields();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Failed to add appointment.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }

    } catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(
            this,
            "Invalid ID value.",
            "Validation Error",
            JOptionPane.WARNING_MESSAGE
    );

} catch (IllegalArgumentException e) {

    JOptionPane.showMessageDialog(
            this,
            "Invalid date or time.\n\n"
            + "Date format: YYYY-MM-DD\n"
            + "Time format: HH:MM:SS",
            "Validation Error",
            JOptionPane.WARNING_MESSAGE
    );
} // TODO add your handling code here:
    }//GEN-LAST:event_btnAddActionPerformed

