    private void loadPatients() {

    cmbPatient.removeAllItems();
    cmbPatient.addItem("Select Patient");

    List<Patient> patients = patientDAO.getAllPatients();

    for (Patient patient : patients) {
        cmbPatient.addItem(
                patient.getPatientId() + " - " + patient.getName()
        );
    }
}
private void loadDentists() {

    cmbDentist.removeAllItems();
    cmbDentist.addItem("Select Dentist");

    List<Dentist> dentists = dentistDAO.getActiveDentists();

    for (Dentist dentist : dentists) {
        cmbDentist.addItem(
                dentist.getDentistId() + " - " + dentist.getName()
        );
    }
}
private void loadTreatments() {

    cmbTreatment.removeAllItems();
    cmbTreatment.addItem("Select Treatment");

    List<Treatment> treatments = treatmentDAO.getAllTreatments();

    for (Treatment treatment : treatments) {

        if ("ACTIVE".equalsIgnoreCase(treatment.getStatus())) {

            cmbTreatment.addItem(
                    treatment.getTreatmentId()
                    + " - "
                    + treatment.getTreatmentName()
            );
        }
    }
}
private void loadAppointments() {

    DefaultTableModel model =
            (DefaultTableModel) tblAppointments.getModel();

    model.setRowCount(0);

    List<Appointment> appointments =
            appointmentDAO.getAllAppointments();

    for (Appointment appointment : appointments) {

        String patientName = "";
        String dentistName = "";
        String treatmentName = "";

        Patient patient =
                patientDAO.findById(appointment.getPatientId());

        if (patient != null) {
            patientName = patient.getName();
        }

        Dentist dentist =
                dentistDAO.findById(appointment.getDentistId());

        if (dentist != null) {
            dentistName = dentist.getName();
        }

        Treatment treatment =
                treatmentDAO.findById(appointment.getTreatmentId());

        if (treatment != null) {
            treatmentName = treatment.getTreatmentName();
        }

        model.addRow(new Object[]{
            appointment.getAppointmentId(),
            appointment.getAppointmentNo(),
            patientName,
            dentistName,
            treatmentName,
            appointment.getAppointmentDate(),
            appointment.getAppointmentTime(),
            appointment.getStatus(),
            appointment.getCreatedBy()
        });
    }
}
